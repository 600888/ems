"""Portable schema comparison and migration safeguards."""

import warnings
import sqlalchemy as sa
from alembic.autogenerate import compare_metadata
from alembic.migration import MigrationContext
from .models import Base


def functional_index(index: sa.Index) -> bool:
    return any(not isinstance(expr, sa.Column) for expr in index.expressions)


def include_object(obj, name, type_, reflected, compare_to):
    """Scope comparisons to EMS and leave function-index migrations to explicit operations."""
    if type_ == "table":
        return name in Base.metadata.tables
    if type_ == "check_constraint":
        # Alembic excludes type-bound Enum checks from metadata but can reflect them as ordinary
        # CHECKs, otherwise reporting every portable enum constraint as something to delete.
        return not any(
            c.name == name and getattr(c, "_type_bound", False)
            for table in Base.metadata.tables.values()
            for c in table.constraints
        )
    if type_ == "index":
        table = Base.metadata.tables.get(obj.table.name)
        if table is not None and any(i.name == name and functional_index(i) for i in table.indexes):
            return False
    return True


def comparison_options(dialect: str) -> dict:
    return {
        "compare_type": True,
        "compare_server_default": True,
        "include_object": include_object,
        "render_as_batch": dialect == "sqlite",
    }


def require_supported(connection: sa.Connection) -> None:
    """Reject incompatible engines before schema/data writes."""
    dialect = connection.dialect
    if dialect.name not in ("sqlite", "mysql", "postgresql"):
        raise ValueError("Supported databases: SQLite, MySQL, PostgreSQL")
    if dialect.name == "mysql" and (
        getattr(dialect, "is_mariadb", False) or dialect.server_version_info < (8, 0, 16)
    ):
        raise ValueError("MySQL 8.0.16+ is required")
    if dialect.name == "sqlite" and dialect.server_version_info < (3, 9, 0):
        raise ValueError("SQLite 3.9+ is required for expression indexes")


def schema_differences(connection: sa.Connection) -> list[str]:
    """Compare tables, columns, defaults, standard indexes, FKs and primary keys.

    Alembic cannot reliably compare CHECK and expression indexes across dialects. Those must be
    reviewed explicitly before adopting an existing database or accepting autogenerated migrations.
    """
    require_supported(connection)
    ctx = MigrationContext.configure(connection, opts=comparison_options(connection.dialect.name))
    with warnings.catch_warnings():
        warnings.filterwarnings(
            "ignore",
            message="Skipped unsupported reflection of expression-based index.*",
            category=sa.exc.SAWarning,
        )
        warnings.filterwarnings(
            "ignore",
            message="autogenerate skipping metadata-specified expression-based index.*",
            category=UserWarning,
        )
        differences = [str(diff) for diff in compare_metadata(ctx, Base.metadata)]
    inspector = sa.inspect(connection)
    existing = set(inspector.get_table_names())
    for table in Base.metadata.sorted_tables:
        if table.name not in existing:
            continue
        if inspector.get_pk_constraint(table.name)["constrained_columns"] != [
            c.name for c in table.primary_key
        ]:
            differences.append(f"{table.name}: primary key differs")
        # Even when reflection omits expressions, require all expected index names to exist.
        if connection.dialect.name == "sqlite":
            indexes = set(
                connection.execute(
                    sa.text(
                        "SELECT name FROM sqlite_master WHERE type='index' AND tbl_name=:table"
                    ),
                    {"table": table.name},
                ).scalars()
            )
        elif connection.dialect.name == "mysql":
            quoted = connection.dialect.identifier_preparer.quote(table.name)
            indexes = {
                r["Key_name"]
                for r in connection.exec_driver_sql(f"SHOW INDEX FROM {quoted}").mappings()
            }
        else:
            indexes = {i["name"] for i in inspector.get_indexes(table.name)}
        for index in table.indexes:
            if functional_index(index) and index.name not in indexes:
                differences.append(f"{table.name}: missing expression index {index.name}")
    return differences
